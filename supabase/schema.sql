-- ---------------------------------------------------------------------
-- 1. CUSTOM TYPES
-- An "enum" is a column type that only accepts a fixed list of values.
-- Why: the database itself rejects typos like 'intervew'. The order
-- below also matters. Postgres treats later values as "greater", which
-- is what lets us ask "did this application get to interview OR
-- further?" in the analytics view.
-- ---------------------------------------------------------------------
create type public.application_stage as enum (
  'saved',          -- on your list, not applied yet
  'applied',
  'assessment',     -- online assessment or take-home
  'phone_screen',
  'interview',
  'final_round',
  'offer'
);

-- Stage = how far you got. Status = what is happening now.
-- Keeping them separate means a rejection never erases how far you got.
create type public.application_status as enum (
  'active',
  'rejected',
  'withdrawn',
  'accepted',
  'declined'
);

create type public.round_outcome as enum ('pending', 'passed', 'failed');


-- ---------------------------------------------------------------------
-- 2. TABLES
-- Every table has:
--   id       a unique identifier generated by the database (primary key)
--   user_id  who owns the row. "default auth.uid()" fills in the
--            logged-in user automatically, so the app never sends it.
-- "references ... on delete cascade" is a foreign key: the value must
-- exist in the other table, and if the parent row is deleted, the child
-- rows are deleted with it.
-- ---------------------------------------------------------------------

create table public.companies (
  id          uuid primary key default gen_random_uuid(),
  user_id     uuid not null default auth.uid() references auth.users (id) on delete cascade,
  name        text not null,
  website     text,
  industry    text,
  created_at  timestamptz not null default now()
);

create table public.applications (
  id              uuid primary key default gen_random_uuid(),
  user_id         uuid not null default auth.uid() references auth.users (id) on delete cascade,
  company_id      uuid not null references public.companies (id) on delete cascade,
  role_title      text not null,
  stage           public.application_stage  not null default 'saved',
  status          public.application_status not null default 'active',
  applied_date    date,
  deadline        date,
  follow_up_date  date,
  job_url         text,
  notes           text,
  created_at      timestamptz not null default now()
);

create table public.interview_rounds (
  id              uuid primary key default gen_random_uuid(),
  user_id         uuid not null default auth.uid() references auth.users (id) on delete cascade,
  application_id  uuid not null references public.applications (id) on delete cascade,
  round_number    integer not null check (round_number > 0),
  round_type      text,              -- e.g. 'behavioral', 'case', 'technical'
  scheduled_at    timestamptz,
  outcome         public.round_outcome not null default 'pending',
  notes           text,
  created_at      timestamptz not null default now()
);

create table public.contacts (
  id                 uuid primary key default gen_random_uuid(),
  user_id            uuid not null default auth.uid() references auth.users (id) on delete cascade,
  company_id         uuid not null references public.companies (id) on delete cascade,
  name               text not null,
  title              text,
  email              text,
  linkedin_url       text,
  last_contacted_at  date,
  notes              text,
  created_at         timestamptz not null default now()
);

-- A log of every stage an application has entered, with a timestamp.
-- The app never writes to this directly. The trigger in section 4 does.
create table public.stage_events (
  id              uuid primary key default gen_random_uuid(),
  user_id         uuid not null default auth.uid() references auth.users (id) on delete cascade,
  application_id  uuid not null references public.applications (id) on delete cascade,
  stage           public.application_stage not null,
  entered_at      timestamptz not null default now()
);


-- ---------------------------------------------------------------------
-- 3. INDEXES
-- An index is like the index at the back of a textbook: it lets the
-- database find rows without scanning the whole table. We index the
-- columns we filter and join on.
-- ---------------------------------------------------------------------
create index companies_user_id_idx            on public.companies (user_id);
create index applications_user_id_idx         on public.applications (user_id);
create index applications_company_id_idx      on public.applications (company_id);
create index interview_rounds_user_id_idx     on public.interview_rounds (user_id);
create index interview_rounds_application_idx on public.interview_rounds (application_id);
create index contacts_user_id_idx             on public.contacts (user_id);
create index contacts_company_id_idx          on public.contacts (company_id);
create index stage_events_user_id_idx         on public.stage_events (user_id);
create index stage_events_application_idx     on public.stage_events (application_id);


-- ---------------------------------------------------------------------
-- 4. AUTOMATIC STAGE LOGGING
-- A trigger is code the database runs by itself when something happens.
-- Here: whenever an application is created or its stage changes, add a
-- row to stage_events.
-- Why in the database and not in React: the log can never be forgotten
-- or skipped, no matter which screen (or future mobile app) makes the
-- change.
-- ---------------------------------------------------------------------
create function public.log_stage_change()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    insert into public.stage_events (application_id, user_id, stage)
    values (new.id, new.user_id, new.stage);
  elsif new.stage is distinct from old.stage then
    insert into public.stage_events (application_id, user_id, stage)
    values (new.id, new.user_id, new.stage);
  end if;
  return new;
end;
$$;

create trigger applications_log_stage
after insert or update of stage on public.applications
for each row execute function public.log_stage_change();


-- ---------------------------------------------------------------------
-- 5. SECURITY
-- Two layers, and you need both:
--
-- (a) GRANTS decide which roles may touch a table at all.
--     "authenticated" is the role Supabase gives to logged-in users.
--     We grant nothing to "anon" (not logged in), so visitors who are
--     not signed in cannot read or write anything.
--
-- (b) ROW LEVEL SECURITY (RLS) decides which ROWS a role can touch.
--     Each policy below says: only rows where user_id is your own id.
--     "using" filters what you can see, change, and delete.
--     "with check" validates what you try to insert or update.
--
-- This is why it is safe for the React app to talk to the database
-- directly: even if someone edits the frontend code, the database
-- still refuses to show them another user's rows.
-- ---------------------------------------------------------------------

grant select, insert, update, delete on public.companies        to authenticated;
grant select, insert, update, delete on public.applications     to authenticated;
grant select, insert, update, delete on public.interview_rounds to authenticated;
grant select, insert, update, delete on public.contacts         to authenticated;
grant select, insert                 on public.stage_events     to authenticated;

alter table public.companies        enable row level security;
alter table public.applications     enable row level security;
alter table public.interview_rounds enable row level security;
alter table public.contacts         enable row level security;
alter table public.stage_events     enable row level security;

create policy "Users manage their own companies"
on public.companies for all to authenticated
using ((select auth.uid()) = user_id)
with check ((select auth.uid()) = user_id);

create policy "Users manage their own applications"
on public.applications for all to authenticated
using ((select auth.uid()) = user_id)
with check ((select auth.uid()) = user_id);

create policy "Users manage their own interview rounds"
on public.interview_rounds for all to authenticated
using ((select auth.uid()) = user_id)
with check ((select auth.uid()) = user_id);

create policy "Users manage their own contacts"
on public.contacts for all to authenticated
using ((select auth.uid()) = user_id)
with check ((select auth.uid()) = user_id);

-- The stage log is read and append only: no update or delete policy,
-- so history cannot be edited.
create policy "Users read their own stage events"
on public.stage_events for select to authenticated
using ((select auth.uid()) = user_id);

create policy "Users add their own stage events"
on public.stage_events for insert to authenticated
with check ((select auth.uid()) = user_id);


-- ---------------------------------------------------------------------
-- 6. ANALYTICS VIEW
-- A view is a saved query that you can read like a table.
-- For each stage it counts how many of your applications got to that
-- stage OR further. Example output:
--   applied 20, assessment 9, phone_screen 8, interview 5, ...
-- Conversion rate between two stages = later count / earlier count.
--
-- "security_invoker = true" makes the view obey the RLS policies of the
-- person querying it. Without it, a view runs with its creator's
-- permissions and would count every user's applications.
-- ---------------------------------------------------------------------
create view public.application_funnel
with (security_invoker = true) as
with furthest as (
  -- the furthest stage each application ever reached
  select application_id, max(stage) as furthest_stage
  from public.stage_events
  group by application_id
),
stages as (
  -- one row per stage in the enum, skipping 'saved' (not applied yet)
  select s as stage
  from unnest(enum_range(null::public.application_stage)) as s
  where s <> 'saved'
)
select
  stages.stage,
  count(furthest.application_id) as applications_reached
from stages
left join furthest on furthest.furthest_stage >= stages.stage
group by stages.stage
order by stages.stage;

grant select on public.application_funnel to authenticated;
